/**
 * Vite plugins for the playground (playground/, served at /playground/):
 * - inlineRefs: gallery examples get their page `src` and drill-down `$ref` files inlined
 *   at import time (as the root vite.config.js does);
 * - playgroundFiles: playground/viewer-shell.html (the single-file viewer from
 *   lib/build.js appShell(), which the page fills with a payload exactly as `yantra build`
 *   does) and playground/sw.js (an offline cache of the playground's own files), plus a
 *   root /sw.js that retires the service worker of the old root-level playground.
 */
import crypto from 'node:crypto';
import path from 'node:path';
import { appShell, resolveBook, resolveLevels, resolvePage, ROOT } from '../../lib/build.js';

export const PLAYGROUND_DIR = 'playground';
const PLAYGROUND_HTML = path.join(ROOT, PLAYGROUND_DIR, 'index.html');

export function inlineRefs() {
  return {
    name: 'yantra-playground-refs',
    enforce: 'pre',
    transform(code, id) {
      const file = id.split('?')[0];
      if (!file.endsWith('.json') || (!code.includes('"$ref"') && !/"kind"\s*:\s*"(page|book)"/.test(code))) return null;
      let payload;
      try {
        payload = JSON.parse(code);
      } catch {
        return null;
      }
      const dir = path.dirname(file);
      const out = payload?.kind === 'book' ? resolveBook(payload, dir, { root: ROOT }) : payload?.kind === 'page' ? resolvePage(payload, dir) : resolveLevels(payload, dir, { root: ROOT });
      return { code: JSON.stringify(out), map: null };
    }
  };
}

/** Every output file the playground page loads: its entry chunk, imports, CSS and assets. */
function playgroundClosure(bundle) {
  const entry = Object.values(bundle).find((c) => c.type === 'chunk' && c.isEntry && c.facadeModuleId && path.resolve(c.facadeModuleId) === PLAYGROUND_HTML);
  if (!entry) throw new Error('playground entry chunk not found');
  const files = new Set();
  const walk = (name) => {
    const c = bundle[name];
    if (!c || files.has(name)) return;
    files.add(name);
    if (c.type !== 'chunk') return;
    for (const f of [...c.imports, ...c.dynamicImports]) walk(f);
    for (const f of c.viteMetadata?.importedCss || []) files.add(f);
    for (const f of c.viteMetadata?.importedAssets || []) files.add(f);
  };
  walk(entry.fileName);
  return [...files];
}

export function playgroundFiles() {
  return {
    name: 'yantra-playground-files',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (!req.url || req.url.split('?')[0] !== `/${PLAYGROUND_DIR}/viewer-shell.html`) return next();
        try {
          res.setHeader('Content-Type', 'text/html; charset=utf-8');
          res.end(appShell());
        } catch (err) {
          res.statusCode = 500;
          res.end(String(err?.message || err));
        }
      });
    },
    generateBundle(_, bundle) {
      this.emitFile({ type: 'asset', fileName: `${PLAYGROUND_DIR}/viewer-shell.html`, source: appShell() });
      const files = [`/${PLAYGROUND_DIR}/`, `/${PLAYGROUND_DIR}/viewer-shell.html`, ...playgroundClosure(bundle).map((f) => `/${f}`)].sort();
      const version = crypto.createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: `${PLAYGROUND_DIR}/sw.js`, source: serviceWorker(files, version) });
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: RETIRED_ROOT_WORKER });
    }
  };
}

/** Cache-first service worker for /playground/: precaches the playground's files, drops older caches. */
function serviceWorker(files, version) {
  return `// Generated by site/build/playground.js: offline cache for the Yantra playground
const PREFIX = 'yantra-site-playground-';
const CACHE = PREFIX + '${version}';
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new URL(f, self.location.origin)))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => (k.startsWith(PREFIX) && k !== CACHE) || k.startsWith('yantra-playground-')).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Pages: network first, so a new deploy shows at once; the cached copy when offline
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match(new URL('./', self.registration.scope))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
}

/**
 * The playground used to live at the site root with a service worker scoped to "/". This
 * replacement takes over that registration once, deletes the old caches and unregisters
 * itself, so the landing page and docs are always served from the network.
 */
const RETIRED_ROOT_WORKER = `// Retires the service worker of the old root-level playground (now at /playground/)
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('yantra-playground-')).map((k) => caches.delete(k))))
    .then(() => self.registration.unregister()));
});
`;
