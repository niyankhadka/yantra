/** The name when it is a built-in icon (own key), otherwise null. */
export const knownIcon = (name) => (typeof name === 'string' && Object.hasOwn(ICONS, name) ? name : null);

export function iconFor(node) {
  const named = node.data?.icon;
  if (typeof named === 'string' && Object.hasOwn(ICONS, named)) return named;
  const type = String(node.type || '').toLowerCase();
  for (const [re, icon] of TYPE_HINTS) if (re.test(type)) return icon;
  return 'cpu';
}

